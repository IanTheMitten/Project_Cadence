"""ASR bench: time six Whisper configs on recorded command utterances, pick per the 2-point WER rule.

Run from harness/: python scripts/asr_bench.py --dir <bench dir> [--out ../docs/preflight/asr-bench.md]
"""
import argparse
import json
import os
import statistics
import sys
import tempfile
import time
from datetime import date

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from cadence_speaker.audio.asr import Asr  # noqa: E402
from cadence_speaker.wakebench import (  # noqa: E402
    AsrResult, load_labels, load_utterances, pair_commands, pick_asr, wer)

CONFIGS = [("small.en", 5), ("small.en", 1), ("base.en", 5), ("base.en", 1),
           ("distil-small.en", 5), ("distil-small.en", 1)]
BASELINE = "small.en/beam5"


def run(directory: str, out: str) -> str:
    labels = load_labels(directory)
    pairs = pair_commands(labels, load_utterances(directory))
    if not pairs:
        raise LookupError("no command utterances found")
    prompted = sum(1 for lab in labels if lab["kind"] == "command")
    refs = [text for text, _ in pairs]
    pcms = []
    for _, path in pairs:
        with open(path, "rb") as f:
            pcms.append(f.read())

    results = []
    p90s = {}
    for model, beam in CONFIGS:
        name = f"{model}/beam{beam}"
        asr = Asr(model, beam)
        asr.transcribe(pcms[0])  # untimed warm-up
        hyps = []
        ms = []
        for pcm in pcms:
            t0 = time.perf_counter()
            hyps.append(asr.transcribe(pcm))
            ms.append((time.perf_counter() - t0) * 1000)
        results.append(AsrResult(name, wer(refs, hyps), statistics.median(ms)))
        p90s[name] = sorted(ms)[int(0.9 * (len(ms) - 1))]
    chosen = pick_asr(results, BASELINE)

    lines = [
        f"# ASR bench (generated by harness/scripts/asr_bench.py on {date.today().isoformat()})",
        "",
        f"Command utterances: {len(pairs)} (of {prompted} prompted).",
        "",
        "| config | WER | median ms | p90 ms |",
        "|---|---|---|---|",
    ]
    for r in results:
        lines.append(f"| {r.name} | {r.wer:.3f} | {r.median_ms:.0f} | {p90s[r.name]:.0f} |")
    lines += [
        "",
        f"Chosen: {chosen.name}",
        "Rule: fastest median within 2 WER points of small.en/beam5.",
        "",
    ]
    report = "\n".join(lines)
    with open(out, "w") as f:
        f.write(report)
    return report


def _selftest() -> str:
    with tempfile.TemporaryDirectory() as d:
        with open(os.path.join(d, "labels-selftest.jsonl"), "w") as f:
            f.write(json.dumps({"t": 1000.0, "kind": "command", "text": "turn it up"}) + "\n")
            f.write(json.dumps({"t": 1100.0, "kind": "command", "text": "pause the music"}) + "\n")
        for stamp in ("1001000", "1101000"):
            with open(os.path.join(d, f"utt-selftest-{stamp}.pcm"), "wb") as f:
                f.write(bytes(32000))
        return run(d, os.path.join(d, "asr-bench.md"))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir")
    ap.add_argument("--out", default="../docs/preflight/asr-bench.md")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    try:
        if args.selftest:
            report = _selftest()
        elif args.dir:
            report = run(args.dir, args.out)
        else:
            ap.error("--dir required unless --selftest")
    except LookupError as e:
        print(str(e), file=sys.stderr)
        return 1
    print(report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
