#!/usr/bin/env python3
"""Wake replay bench: same recordings through openWakeWord and microWakeWord, win rule applied.

Writes docs/preflight/wake-bench.md. `--selftest` runs the pipeline on synthetic audio.
"""
import argparse
import json
import os
import sys
import tempfile
from datetime import date

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from cadence.audio.wakeword import WAKE_FRAME_BYTES  # noqa: E402
from cadence.config import WAKE_MODEL, WAKE_THRESHOLD  # noqa: E402
from cadence.wakebench import (  # noqa: E402
    Recording, background_seconds, board_wins, detections, evaluate, guided_spans, hit_rate,
    load_labels, load_recordings, sweep)

MWW_CHUNK_BYTES = 3200
CONDITIONS = ("quiet", "music")
DISTANCES = (1, 3, 5)


def oww_trace(rec: Recording) -> list[tuple[float, float]]:
    from openwakeword.model import Model

    model = Model(wakeword_models=[WAKE_MODEL], inference_framework="onnx")
    trace = []
    with open(rec.pcm_path, "rb") as f:
        k = 0
        while len(frame := f.read(WAKE_FRAME_BYTES)) == WAKE_FRAME_BYTES:
            score = model.predict(np.frombuffer(frame, np.int16))[WAKE_MODEL]
            trace.append((rec.start_wall + (k + 1) * 0.08, float(score)))
            k += 1
    return trace


def mww_trace(rec: Recording) -> list[tuple[float, float]]:
    from pymicro_wakeword import MicroWakeWord, MicroWakeWordFeatures, Model

    feats = MicroWakeWordFeatures()
    mww = MicroWakeWord.from_builtin(Model.HEY_JARVIS)
    trace = []
    k = 0
    with open(rec.pcm_path, "rb") as f:
        while chunk := f.read(MWW_CHUNK_BYTES):
            for feature in feats.process_streaming(chunk):
                p = mww.process_streaming_prob(feature)
                if p is not None:
                    trace.append((rec.start_wall + (k + 1) * 0.010, float(p)))
                k += 1
    return trace


def _engine_rows(name, default, swept):
    rows = []
    for label, r in (("default", default), ("swept", swept)):
        rows.append(f"| {name} | {label} | {r.threshold} | {r.hit_rate:.0%} | {r.false_wakes} "
                    f"| {r.fw_per_hour:.3f} | {'yes' if r.target_met else 'no'} |")
    return rows


def run(directory: str, out: str) -> str:
    from pymicro_wakeword import MicroWakeWord, Model

    recs = load_recordings(directory)
    labels = load_labels(directory)
    spans = guided_spans(labels)
    bg = background_seconds(recs, spans)
    wakes = [lab for lab in labels if lab["kind"] == "wake"]
    times = [lab["t"] for lab in wakes]
    oww_traces = [oww_trace(r) for r in recs]
    mww_traces = [mww_trace(r) for r in recs]
    mww_default_th = MicroWakeWord.from_builtin(Model.HEY_JARVIS).probability_cutoff

    results = {}
    for name, traces, th in (("openWakeWord", oww_traces, WAKE_THRESHOLD),
                             ("microWakeWord", mww_traces, mww_default_th)):
        results[name] = (traces, evaluate(traces, times, spans, bg, th),
                         sweep(traces, times, spans, bg))
    oww_sw, mww_sw = results["openWakeWord"][2], results["microWakeWord"][2]

    lines = [
        f"# Wake bench (generated by harness/scripts/wake_bench.py on {date.today().isoformat()})",
        "",
        f"Background audio: {bg / 3600:.2f} h. Positive attempts: {len(times)}.",
        "",
        "| engine | thresholds | threshold | hit rate | false wakes | false wakes/h | target met |",
        "|---|---|---|---|---|---|---|",
    ]
    for name in ("openWakeWord", "microWakeWord"):
        lines += _engine_rows(name, results[name][1], results[name][2])
    lines += ["", "## Hit rate by condition (swept thresholds)", "",
              "| condition | distance m | attempts | openWakeWord | microWakeWord |",
              "|---|---|---|---|---|"]
    events = {name: [e for tr in results[name][0] for e in detections(tr, results[name][2].threshold)]
              for name in results}
    for cond in CONDITIONS:
        for dist in DISTANCES:
            ts = [lab["t"] for lab in wakes
                  if lab.get("condition") == cond and lab.get("distance_m") == dist]
            cells = [f"{hit_rate(events[n], ts):.0%}" if ts else "n/a"
                     for n in ("openWakeWord", "microWakeWord")]
            lines.append(f"| {cond} | {dist} | {len(ts)} | {cells[0]} | {cells[1]} |")
    if board_wins(mww_sw, oww_sw):
        winner = f"Winner: board (microWakeWord, threshold {mww_sw.threshold})"
    else:
        winner = f"Winner: server (openWakeWord, threshold {oww_sw.threshold})"
    lines += ["", "## Verdict", "", winner, "",
              "Rule: board wins unless server hit rate >= board + 10 points, or board false "
              "wakes >= 2x max(server false wakes, 1); applied at swept thresholds.", ""]
    report = "\n".join(lines)
    with open(out, "w") as f:
        f.write(report)
    return report


def _selftest() -> str:
    with tempfile.TemporaryDirectory() as d:
        with open(os.path.join(d, "selftest-1000000.json"), "w") as f:
            json.dump({"start_wall": 1000.0}, f)
        with open(os.path.join(d, "selftest-1000000.pcm"), "wb") as f:
            f.write(bytes(60 * 32000))
        with open(os.path.join(d, "labels-selftest.jsonl"), "w") as f:
            for lab in ({"kind": "session_start", "t": 1000.0},
                        {"kind": "wake", "t": 1005.0, "distance_m": 3, "condition": "quiet"},
                        {"kind": "session_end", "t": 1010.0}):
                f.write(json.dumps(lab) + "\n")
        return run(d, os.path.join(d, "wake-bench.md"))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default=os.environ.get("CADENCE_BENCH_RECORD_DIR", "bench_audio"))
    ap.add_argument("--out", default="../docs/preflight/wake-bench.md")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    print(_selftest() if args.selftest else run(args.dir, args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
